#!/usr/bin/env node
// Regenerate deterministic server font bytes from the exact Google Fonts faces
// used by index.html and the /branding theme. Pinned URLs; no runtime network.
// Run from any directory: node remix/scripts/generate-social-card-brand-fonts.mjs
import { writeFileSync } from 'node:fs';
const faces = [
  {
    "family": "Hanken Grotesk",
    "weight": 400,
    "file": "HankenGrotesk-400.ttf",
    "source": "https://fonts.gstatic.com/s/hankengrotesk/v12/ieVq2YZDLWuGJpnzaiwFXS9tYvBRzyFLlZg_f_Ncs2Za4Q.ttf"
  },
  {
    "family": "Hanken Grotesk",
    "weight": 700,
    "file": "HankenGrotesk-700.ttf",
    "source": "https://fonts.gstatic.com/s/hankengrotesk/v12/ieVq2YZDLWuGJpnzaiwFXS9tYvBRzyFLlZg_f_NcVGFa4Q.ttf"
  },
  {
    "family": "JetBrains Mono",
    "weight": 500,
    "file": "JetBrainsMono-500.ttf",
    "source": "https://fonts.gstatic.com/s/jetbrainsmono/v24/tDbY2o-flEEny0FZhsfKu5WU4zr3E_BX0PnT8RD8-qxjPQ.ttf"
  },
  {
    "family": "Space Grotesk",
    "weight": 700,
    "file": "SpaceGrotesk-700.ttf",
    "source": "https://fonts.gstatic.com/s/spacegrotesk/v22/V8mQoQDjQSkFtoMM3T6r8E7mF71Q-gOoraIAEj4PVksj.ttf"
  }
];
const entries = [];
for (const face of faces) {
  const response = await fetch(face.source);
  if (!response.ok) throw new Error(`Font download failed: ${face.family} ${response.status}`);
  entries.push({ ...face, base64: Buffer.from(await response.arrayBuffer()).toString('base64') });
}
const source = '// GENERATED by scripts/generate-social-card-brand-fonts.mjs.\n' +
  '// Exact /branding families from index.html. Bundled for deterministic resvg output.\n' +
  '// SIL Open Font License 1.1; see LICENSE-{SpaceGrotesk,HankenGrotesk,JetBrainsMono}.txt.\n' +
  'export const SOCIAL_CARD_BRAND_FONTS = ' + JSON.stringify(entries, null, 2) + ' as const;\n';
writeFileSync(new URL('../app/api/utils/meta/socialCardBrandFontData.ts', import.meta.url), source);
console.log('Regenerated canonical social-card brand fonts.');
