import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { readFile, mkdir, mkdtemp, rm, writeFile } from 'node:fs/promises';
import { createServer } from 'node:http';
import { once } from 'node:events';
import { join, resolve } from 'node:path';
import { tmpdir } from 'node:os';
const root = resolve(import.meta.dirname, '..'), require = createRequire(join(root, '../MCP/package.json'));
const evidence = resolve(process.argv[2] || join(tmpdir(), 'thingtime-device-debug-ui'));
const dir = await mkdtemp(join(tmpdir(), 'thingtime-device-debug-ui-'));
let server, context, page;
const errors = [], passed = [];
try {
	await mkdir(evidence, { recursive: true });
	await require('esbuild').build({ entryPoints: [join(root, 'scripts/device-debug.browser.tsx')], bundle: true, format: 'esm', platform: 'browser', target: 'esnext', outfile: join(dir, 'fixture.js'), tsconfig: join(root, 'tsconfig.json'), define: { 'process.env.NODE_ENV': '"development"' }, loader: { '.wasm': 'file' }, logLevel: 'error' });
	const bundle = await readFile(join(dir, 'fixture.js'));
	server = createServer((req, res) => { res.writeHead(200, { 'Content-Type': req.url === '/fixture.js' ? 'application/javascript' : 'text/html', 'Cache-Control': 'no-store' }); res.end(req.url === '/fixture.js' ? bundle : '<!doctype html><title>[QA] Private device activity</title><meta name="viewport" content="width=device-width,initial-scale=1"><div id="root"></div><script type="module" src="/fixture.js"></script>'); });
	server.listen(28453, '127.0.0.1'); await once(server, 'listening');
	context = await require('playwright').chromium.launchPersistentContext(join(dir, 'profile'), { headless: true, acceptDownloads: true });
	page = context.pages()[0]; page.on('pageerror', e => errors.push(e.message));
	await page.goto('http://127.0.0.1:28453/things/debug');
	await page.getByText('6 saved events shown', { exact: true }).waitFor();
	for (const [name, width, height] of [['phone', 390, 844], ['desktop', 1280, 900]]) {
		await page.setViewportSize({ width, height });
		await page.getByText('Event details', { exact: true }).first().click();
		await page.getByText('NSURLErrorDomain · -1009', { exact: true }).waitFor();
		await page.getByText('Diagnostics settings', { exact: true }).click();
		for (let y = 0; y < await page.evaluate(() => document.documentElement.scrollHeight); y += height / 2) await page.evaluate(y => scrollTo(0, y), y);
		assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), name + ' no horizontal overflow');
		await page.screenshot({ path: join(evidence, name + '-details.png'), fullPage: true });
		await page.getByText('Event details', { exact: true }).first().click();
		await page.getByText('Diagnostics settings', { exact: true }).click();
	}
	passed.push('Desktop/phone opened details and settings, full-page scroll, no overflow.');
	await page.getByRole('button', { name: 'Load older events' }).click(); await page.getByText('12 saved events shown', { exact: true }).waitFor();
	await page.getByLabel('Severity', { exact: true }).selectOption('error'); await page.getByText('1 saved event shown', { exact: true }).waitFor();
	const [download] = await Promise.all([page.waitForEvent('download'), page.getByRole('button', { name: 'Export shown events' }).click()]);
	await download.saveAs(join(evidence, 'shown-events.json')); assert.equal(JSON.parse(await readFile(join(evidence, 'shown-events.json'), 'utf8')).events.length, 1);
	passed.push('Server-filtered pagination and explicitly shown-only export.');
	await page.evaluate(() => { window.debugFixture.fail(true); dispatchEvent(new Event('offline')); });
	await page.getByRole('button', { name: 'Refresh', exact: true }).click(); await page.getByRole('alert').filter({ hasText: 'Device activity is unavailable' }).waitFor();
	assert.equal(await page.getByText('Error · Sync failed', { exact: true }).count(), 1);
	await page.evaluate(() => { window.debugFixture.fail(false); dispatchEvent(new Event('online')); });
	await page.getByRole('button', { name: 'Try again' }).click(); await page.getByText('1 saved event shown', { exact: true }).waitFor();
	await page.getByLabel('Severity', { exact: true }).selectOption('warning'); await page.getByText('No events match these filters.', { exact: false }).waitFor();
	passed.push('Offline failure retains events; explicit retry and empty filter recover.');
	await page.getByLabel('Severity', { exact: true }).selectOption(''); await page.getByText('6 saved events shown', { exact: true }).waitFor();
	await page.getByRole('button', { name: 'Builder on current page' }).click();
	await page.getByRole('button', { name: 'Edit layout', exact: true }).click();
	await page.screenshot({ path: join(evidence, 'builder-open.png'), fullPage: true });
	await page.locator('[data-block-id="debug-title"]').click();
	if (!await page.getByLabel('Block text', { exact: true }).isVisible()) await page.getByTestId('builder-drawer-reopen').click();
	await page.getByLabel('Block text', { exact: true }).fill('Device activity');
	await page.getByTestId('builder-close').click();
	await page.locator('[data-block-id="debug-field-reason-label"]').click();
	if (!await page.getByLabel('Block text', { exact: true }).isVisible()) await page.getByTestId('builder-drawer-reopen').click();
	await page.getByLabel('Block text', { exact: true }).fill('Wait reason');
	await page.getByTestId('builder-close').click();
	await page.locator('[data-block-id="debug-field-reason"]').click();
	if (!await page.getByLabel('Block text', { exact: true }).isVisible()) await page.getByTestId('builder-drawer-reopen').click();
	assert.equal(await page.getByLabel('Block text', { exact: true }).inputValue(), '{item.reasonLabel}');
	await page.getByTestId('builder-close').click();
	await page.getByRole('button', { name: 'Save layout', exact: true }).click();
	await page.getByRole('button', { name: 'Done editing layout', exact: true }).click();
	await page.reload(); await page.getByRole('heading', { name: 'Device activity', exact: true }).waitFor();
	await page.getByText('Event details', { exact: true }).first().click(); await page.getByText('Wait reason', { exact: true }).first().waitFor();
	passed.push('Builder selects and edits heading and nested repeated label independently, retains the bound value, saves and reloads. Rendering fixture storage only.');
	await page.getByText('Diagnostics settings', { exact: true }).click();
	await page.getByRole('button', { name: 'Pause diagnostics capture', exact: true }).click(); await page.getByRole('button', { name: 'Enable diagnostics capture', exact: true }).waitFor();
	await page.getByText('Clear diagnostic history', { exact: true }).click(); await page.getByRole('button', { name: 'Clear saved events', exact: true }).click();
	await page.getByRole('button', { name: 'Confirm clear all saved events', exact: true }).click(); await page.getByText('0 saved events shown', { exact: true }).waitFor();
	passed.push('Capture requires saved readback; clear requires explicit second confirmation and returns an empty history.');
	await page.goto('http://127.0.0.1:28453/things/debug?remote');
	await page.getByText('6 saved events shown', { exact: true }).waitFor();
	await page.evaluate(() => window.debugFixture.badFallback(true));
	await page.getByRole('button', { name: 'Refresh', exact: true }).click();
	await page.getByRole('alert').filter({ hasText: 'Device activity is unavailable' }).waitFor();
	assert.equal(await page.getByText('Error · Sync failed', { exact: true }).count(), 1);
	passed.push('Real useApi expected-origin transport accepts a selected API different from the renderer and rejects a missing fallback receipt.');
	await page.evaluate(() => { window.debugFixture.badFallback(false); window.debugFixture.retireIdentity(); });
	await page.getByRole('button', { name: 'Try again', exact: true }).click();
	await page.getByRole('alert').filter({ hasText: 'diagnostics account or selected server changed' }).waitFor();
	assert.equal(await page.getByText('Error · Sync failed', { exact: true }).count(), 0);
	passed.push('A retired root identity clears already-rendered private events through real useApi before any parent remount.');
	assert.deepEqual(errors, []);
	await writeFile(join(evidence, 'results.json'), JSON.stringify({ passed, errors, isolatedProfile: true, mockedRenderingOnly: true }, null, 2));
	console.log(JSON.stringify({ passed: passed.length, evidence }));
} catch (error) {
	await page?.screenshot({ path: join(evidence, 'failure.png'), fullPage: true }).catch(() => {});
	await writeFile(join(evidence, 'failure.json'), JSON.stringify({ error: String(error), errors, trace: await page?.evaluate(() => window.debugFixture?.trace).catch(() => []), body: await page?.locator('body').innerText().catch(() => '') }, null, 2)); throw error;
} finally { await context?.close(); await new Promise(resolve => server ? server.close(resolve) : resolve()); await rm(dir, { recursive: true, force: true }); }
