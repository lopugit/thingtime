import React from 'react';
import { Box, Button, Flex, Modal, ModalBody, ModalContent, ModalFooter, ModalHeader, ModalOverlay, Select, Text, Textarea } from '@chakra-ui/react';

type Account = { id: string; label: string; connected: boolean };
type Recipient = { version: 1; id: string; targetOrigin: string; targetOwnerId: string; publicKey: string; nonce: string; expiresAt: number };

// Transfer bytes remain transient. The recipient code is public; the package
// contains ciphertext sealed for that destination, never an OAuth bearer token.
export const ChatGPTPlanTransfer = ({ accounts, disabled, request, refresh }: {
  accounts: Account[];
  disabled: boolean;
  request: (body: Record<string, unknown>) => Promise<any>;
  refresh: () => Promise<unknown>;
}) => {
  const [expanded, setExpanded] = React.useState(false);
  const [recipientCode, setRecipientCode] = React.useState('');
  const [destinationCode, setDestinationCode] = React.useState('');
  const [accountId, setAccountId] = React.useState('');
  const [recipient, setRecipient] = React.useState<Recipient | null>(null);
  const [bundle, setBundle] = React.useState('');
  const [busy, setBusy] = React.useState(false);
  const [message, setMessage] = React.useState('');
  const selectedAccount = accounts.find(account => account.id === accountId);
  const live = React.useRef(true);
  const operation = React.useRef(false);
  React.useEffect(() => { live.current = true; return () => { live.current = false; }; }, []);
  const run = async (work: () => Promise<void>) => {
    if (operation.current || disabled) return;
    operation.current = true; setBusy(true); setMessage('');
    try { await work(); }
    catch { if (live.current) setMessage('Transfer could not complete. Check the destination, account and expiry, then retry. If a move response was lost, retry with the same destination code to recover its encrypted package.'); }
    finally { operation.current = false; if (live.current) setBusy(false); }
  };
  const prepare = () => run(async () => {
    const data = await request({ action: 'prepare-import' });
    if (live.current) { setRecipientCode(JSON.stringify(data.result)); setMessage('Copy this destination code to the runtime that currently holds your ChatGPT connection.'); }
  });
  const reviewMove = () => {
    try {
      if (!accountId || destinationCode.length > 16_384) throw new Error();
      const parsed = JSON.parse(destinationCode) as Recipient;
      const url = new URL(parsed.targetOrigin);
      if (parsed.version !== 1 || !parsed.id || !parsed.targetOwnerId || !parsed.publicKey || !parsed.nonce ||
        url.origin !== parsed.targetOrigin || url.username || url.password ||
        !(url.protocol === 'https:' || (url.protocol === 'http:' && ['127.0.0.1', 'localhost', '[::1]'].includes(url.hostname))) ||
        !Number.isFinite(parsed.expiresAt) || parsed.expiresAt <= Date.now()) throw new Error();
      setRecipient(parsed); setMessage('');
    } catch { setMessage('Choose a connection and paste a current destination code generated by your destination runtime.'); }
  };
  const move = () => run(async () => {
    if (!recipient) return;
    const data = await request({ action: 'move-account', id: accountId, recipient });
    if (!live.current) return;
    setBundle(JSON.stringify(data.result)); setRecipient(null);
    setMessage('The source connection has stopped. Download its encrypted package and import it at the destination.');
    await refresh();
  });
  const download = () => {
    if (!bundle) return;
    const url = URL.createObjectURL(new Blob([bundle], { type: 'application/json' }));
    const anchor = document.createElement('a'); anchor.href = url; anchor.download = 'thingtime-chatgpt-transfer.json'; anchor.click();
    setTimeout(() => URL.revokeObjectURL(url), 1000);
  };
  const importFile = (file?: File) => run(async () => {
    if (!file || file.size > 128 * 1024) throw new Error();
    const value = JSON.parse(await file.text());
    const data = await request({ action: 'import-account', bundle: value });
    if (!live.current || !data.result?.id) return;
    setMessage('Connection imported. Choose its model, then select this account in Lopu.');
    await refresh();
  });
  return <Box mt={4} borderTop="1px solid var(--tt-border, #ececef)" pt={3}>
    <Button size="sm" variant="ghost" onClick={() => setExpanded(value => !value)} aria-expanded={expanded}>Move between runtimes</Button>
    {expanded ? <Flex direction="column" gap={3} mt={3} minW={0}>
      <Text fontSize="sm">Connect locally, then move a connection to another runtime you control. Your API runs requests; its configured database stores the encrypted connection. A move stops this source from using or refreshing it.</Text>
      <Text fontSize="sm" fontWeight={600}>1. Prepare the destination</Text>
      <Button alignSelf="start" size="sm" isDisabled={disabled || busy} onClick={() => void prepare()}>Create destination code</Button>
      {recipientCode ? <Textarea aria-label="Destination code" value={recipientCode} isReadOnly fontFamily="mono" fontSize="xs" overflowWrap="anywhere" minH="100px" /> : null}
      <Text fontSize="xs">Generate this code while signed in to the destination API, then copy it into the source below. It identifies the receiving account and expires shortly.</Text>
      <Text fontSize="sm" fontWeight={600}>2. Move from the source</Text>
      <Select aria-label="Connection to move" value={accountId} onChange={event => setAccountId(event.target.value)} isDisabled={disabled || busy} minW={0}>
        <option value="">Choose a ChatGPT connection</option>
        {accounts.filter(account => account.connected || account.id === accountId).map(account => <option key={account.id} value={account.id}>{account.label} · {account.id.slice(-8)}</option>)}
      </Select>
      {selectedAccount ? <Text fontSize="xs" overflowWrap="anywhere">Selected connection: {selectedAccount.label} · {selectedAccount.id.slice(-8)}</Text> : null}
      <Textarea aria-label="Receiving runtime destination code" placeholder="Paste the destination code" value={destinationCode} maxLength={16_384} onChange={event => setDestinationCode(event.target.value)} isDisabled={disabled || busy} fontFamily="mono" fontSize="xs" minH="100px" />
      <Button alignSelf="start" size="sm" isDisabled={disabled || busy || !accountId || !destinationCode} onClick={reviewMove}>Review move</Button>
      {bundle ? <Button alignSelf="start" size="sm" onClick={download}>Download encrypted transfer</Button> : null}
      <Text fontSize="sm" fontWeight={600}>3. Import at the destination</Text>
      <Text as="label" fontSize="sm">Encrypted transfer file<input type="file" accept="application/json,.json" aria-label="Encrypted ChatGPT transfer file" disabled={disabled || busy} style={{ display: 'block', maxWidth: '100%', marginTop: 8 }} onChange={event => { const file = event.target.files?.[0]; event.target.value = ''; void importFile(file); }} /></Text>
      {message ? <Text role="status" fontSize="sm" overflowWrap="anywhere">{message}</Text> : null}
    </Flex> : null}
    <Modal isOpen={Boolean(recipient)} onClose={() => { if (!busy) setRecipient(null); }} isCentered size="md">
      <ModalOverlay /><ModalContent mx={4} maxH="calc(100dvh - 32px)" overflowY="auto">
        <ModalHeader>Move this ChatGPT connection?</ModalHeader>
        <ModalBody>
          <Text>This runtime will stop using the connection. Only the runtime that created this destination code can decrypt the transfer.</Text>
          <Text mt={3} fontSize="sm" overflowWrap="anywhere">Moving connection: {selectedAccount?.label} · {selectedAccount?.id.slice(-8)}</Text>
          <Text mt={3} fontWeight={600} overflowWrap="anywhere">{recipient?.targetOrigin}</Text>
          <Text mt={1} fontSize="sm" overflowWrap="anywhere">Receiving account: {recipient?.targetOwnerId}</Text>
          <Text mt={3} fontSize="sm">Confirm that this is your intended API and account. Keep the encrypted package until the import succeeds.</Text>
        </ModalBody>
        <ModalFooter gap={2} flexWrap="wrap"><Button variant="ghost" isDisabled={busy} onClick={() => setRecipient(null)}>Cancel</Button><Button isLoading={busy} isDisabled={disabled} onClick={() => void move()}>Move connection</Button></ModalFooter>
      </ModalContent>
    </Modal>
  </Box>;
};
